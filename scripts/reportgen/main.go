package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"
)

type Metadata struct { Environment string `json:"environment"`; Commit string `json:"commit"`; Notes string `json:"notes"` }
func main() {
	meta := Metadata{Environment:"local", Commit:"unknown", Notes:"Evidence generated by scripts/run_experiments.sh"}
	if b, err := os.ReadFile("evidence/metadata.json"); err == nil { _ = json.Unmarshal(b, &meta) }
	entries, _ := os.ReadDir("evidence/raw")
	var files []string
	for _, e := range entries { if !e.IsDir() && !strings.HasSuffix(e.Name(), ".html") { files = append(files, e.Name()) } }
	content := fmt.Sprintf("# Payment Mesh Experiment Report\n\nGenerated: %s\n\n## Reproducibility\n\n- Environment: `%s`\n- Commit: `%s`\n- Notes: %s\n\n## Scenarios\n\n| Scenario | Evidence |\n|---|---|\n", time.Now().UTC().Format(time.RFC3339), meta.Environment, meta.Commit, meta.Notes)
	for _, f := range files { content += fmt.Sprintf("| `%s` | [evidence/raw/%s](evidence/raw/%s) |\n", strings.TrimSuffix(f, filepath.Ext(f)), f, f) }
	content += "\n## Interpretation\n\nThe expected invariants are: one effective provider charge per idempotency key; payload reuse with a different body returns `409`; definitive provider declines are `FAILED`; uncertain timeout/5xx/circuit-open outcomes are `PENDING`; mTLS and authorization policies are applied only in Kubernetes.\n\n## Limitations\n\nCluster and Istio results are marked as not executed unless the runner produced evidence. Re-run the commands in `docs/running.md` on a host with Kubernetes and Istio to complete those rows.\n"
	if err := os.WriteFile("report.md", []byte(content), 0644); err != nil { panic(err) }
}
